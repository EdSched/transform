言語文化学系 **表象文化**

表象文化研究是一门跨学科的人文社会科学，探讨文化现象如何与社会结构、政治权力、经济机制与身份认同互动。起源于英国伯明翰学派，强调对大众文化、媒介表象与权力关系的批判性分析。

**知识结构**

**▸ 表象与符号分析——**影视·广告·文学中的表象机制与意识形态结构

**▸ 文化政治经济学——**文化生产·流通·消费背后的制度与资本逻辑

**▸ 身份政治与社会正义——**性别·阶级·种族如何在文化中被建构与再生产

**▸ 全球化与在地文化——**全球文化流动与本地文化重构机制

**▸ 视觉文化与媒体研究——**从动漫·游戏到网络文化的当代表象分析

